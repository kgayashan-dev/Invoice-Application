"use client";

import { useEffect, useState, useMemo } from "react";
import { History, Shield, Filter, Search } from "lucide-react";
import DarkPageHeader from "@/components/DarkPageHeader";
import PageShell from "@/components/layout/PageShell";
import PageToolbar from "@/components/layout/PageToolbar";
import DataTable, { ColumnDef } from "@/components/data/DataTable";
import StatusBadge from "@/components/feedback/StatusBadge";
import { getApiBaseUrl } from "@/app/login/action";
import { getAuthHeaders } from "@/utils/auth";

interface AuditLogItem {
  id: number;
  timestamp: string;
  userName: string;
  action: string;
  module: string;
  details?: string;
  ipAddress?: string;
}

export default function AuditPage() {
  const [logs, setLogs] = useState<AuditLogItem[]>([]);
  const [moduleFilter, setModuleFilter] = useState("ALL");
  const [searchTerm, setSearchTerm] = useState("");
  const [loading, setLoading] = useState(true);

  const fetchLogs = async () => {
    setLoading(true);
    try {
      const apiUrl = getApiBaseUrl();
      const res = await fetch(`${apiUrl}/api/Audit?module=${moduleFilter}&limit=200`, {
        headers: getAuthHeaders(),
      });
      if (res.ok) {
        const data = await res.json();
        setLogs(Array.isArray(data) ? data : []);
      }
    } catch {
      // ignore
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchLogs();
  }, [moduleFilter]);

  const filteredLogs = useMemo(() => {
    if (!searchTerm.trim()) return logs;
    const s = searchTerm.toLowerCase();
    return logs.filter(
      (l) =>
        l.userName.toLowerCase().includes(s) ||
        l.action.toLowerCase().includes(s) ||
        l.module.toLowerCase().includes(s) ||
        (l.details && l.details.toLowerCase().includes(s))
    );
  }, [logs, searchTerm]);

  const columns: ColumnDef<AuditLogItem>[] = [
    {
      header: "Timestamp",
      cell: (row) => (
        <span className="font-mono text-xs text-slate-500 whitespace-nowrap">
          {new Date(row.timestamp).toLocaleString()}
        </span>
      ),
    },
    {
      header: "Operator",
      cell: (row) => (
        <span className="font-semibold text-slate-900 text-xs font-mono">
          @{row.userName}
        </span>
      ),
    },
    {
      header: "Action",
      cell: (row) => (
        <span className="inline-flex items-center px-2 py-0.5 rounded-md font-mono text-[11px] font-bold bg-slate-100 text-slate-800 border border-slate-200">
          {row.action}
        </span>
      ),
    },
    {
      header: "Module",
      cell: (row) => (
        <span className="text-xs text-slate-600 font-semibold uppercase tracking-wider">
          {row.module}
        </span>
      ),
    },
    {
      header: "Audit Details",
      cell: (row) => (
        <span className="text-xs text-slate-700">
          {row.details || "—"}
        </span>
      ),
    },
    {
      header: "Client IP",
      cell: (row) => (
        <span className="font-mono text-[11px] text-slate-400">
          {row.ipAddress || "—"}
        </span>
      ),
    },
  ];

  return (
    <PageShell>
      <DarkPageHeader
        icon={<History className="w-4 h-4 text-cyan-400" />}
        breadcrumbs={["Home", "Administration", "Audit Trail"]}
        pageTitle="Security Audit Trail"
        description="Immutable system change logs generated by SQL Server stored procedures"
        onRefresh={fetchLogs}
        isRefreshing={loading}
      />

      <PageToolbar
        searchValue={searchTerm}
        onSearchChange={setSearchTerm}
        searchPlaceholder="Filter audit records by operator, action, details..."
        count={filteredLogs.length}
        countLabel="records"
        filters={
          <div className="flex items-center gap-1.5">
            {["ALL", "AUTH", "ADMIN_USERS", "SETTINGS", "INVOICES"].map((m) => (
              <button
                key={m}
                onClick={() => setModuleFilter(m)}
                className={`px-2.5 py-1 text-xs font-semibold rounded-md transition-colors ${
                  moduleFilter === m
                    ? "bg-blue-600 text-white shadow-2xs"
                    : "bg-white text-slate-600 hover:bg-slate-50 border border-slate-200"
                }`}
              >
                {m === "ALL" ? "All Modules" : m}
              </button>
            ))}
          </div>
        }
      />

      <div className="bg-white rounded-lg border border-slate-200 shadow-2xs overflow-hidden">
        <DataTable
          data={filteredLogs}
          columns={columns}
          keyField="id"
          loading={loading}
          emptyMessage="No audit logs recorded for this criteria."
        />
      </div>
    </PageShell>
  );
}
